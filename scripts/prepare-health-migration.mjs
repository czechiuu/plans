import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
const migrations = [
  ['202610130001', 'initial', '1d56c15aa7609c057d53a05b124b172d'],
  ['202610130002', 'space_lock_order', 'c1e2788c3d67dccb544ab8166a6c096b'],
  ['202610130003', 'fixed_accounts', 'd13a863ec3337d16a4a968835d5ee12d'],
  ['202610130004', 'health_daily', '9a430516e9a44d8d27c651cf24e73e2b'],
];
const source = [];
for (const [version, name, expected] of migrations) {
  const path = new URL(`supabase/migrations/${version}_${name}.sql`, root);
  const sql = (await readFile(path, 'utf8')).replace(/\r\n/g, '\n');
  const actual = createHash('md5').update(sql, 'utf8').digest('hex');
  if (actual !== expected) throw new Error(`Migration ${version} source hash changed`);
  source.push(sql);
}
const body = source[3];
if (body.includes('$health004_body$') || body.includes('$health004_apply$')) {
  throw new Error('Migration contains deployment quote delimiter');
}

const sql = `-- Generated by scripts/prepare-health-migration.mjs. No credentials or user IDs.
-- Paste this entire file into this project's Supabase SQL Editor once. Re-running
-- is safe only if the stored 004 statement matches the source exactly.
begin;
lock table supabase_migrations.schema_migrations in share row exclusive mode;
do $health004_apply$
declare
  v_source text := $health004_body$${body}$health004_body$;
  v_registered text[];
  v_name text;
  v_expected record;
  v_count integer;
begin
  for v_expected in
    select * from (values
      ('202610130001', '1d56c15aa7609c057d53a05b124b172d'),
      ('202610130002', 'c1e2788c3d67dccb544ab8166a6c096b'),
      ('202610130003', 'd13a863ec3337d16a4a968835d5ee12d')
    ) as required(version, source_md5)
  loop
    select statements into v_registered
      from supabase_migrations.schema_migrations where version=v_expected.version;
    if not found or cardinality(v_registered) is distinct from 1
       or md5(v_registered[1]) is distinct from v_expected.source_md5 then
      raise exception 'Migration history mismatch: %', v_expected.version;
    end if;
  end loop;

  -- The migration is only valid for the existing, confirmed two-account space.
  select count(*) into v_count from public.fixed_accounts f
    join auth.users u on u.id=f.user_id
    join public.members m on m.user_id=f.user_id and m.space_id=f.space_id
    where (f.slot='me' and u.email='me@plans.invalid'
        or f.slot='w' and u.email='w@plans.invalid')
      and u.email_confirmed_at is not null
      and nullif(u.encrypted_password,'') is not null;
  if v_count <> 2
     or (select count(*) from public.fixed_accounts) <> 2
     or (select count(*) from auth.users) <> 2
     or (select count(distinct space_id) from public.fixed_accounts) <> 1
     or (select count(*) from public.members) <> 2 then
    raise exception 'Fixed two-account space precondition failed';
  end if;

  select statements,name into v_registered,v_name
    from supabase_migrations.schema_migrations where version='202610130004';
  if found then
    if cardinality(v_registered) is distinct from 1
       or md5(v_registered[1]) is distinct from '9a430516e9a44d8d27c651cf24e73e2b'
       or v_name is distinct from 'health_daily' then
      raise exception 'Migration history mismatch: 202610130004';
    end if;
    return;
  end if;

  execute v_source;
  insert into supabase_migrations.schema_migrations(version,statements,name)
    values ('202610130004',array[v_source],'health_daily');
end
$health004_apply$;
commit;
`;
const output = new URL('supabase/admin/apply-health-004.sql', root);
await writeFile(output, sql, 'utf8');
console.log(`Prepared ${fileURLToPath(output)} (${Buffer.byteLength(sql)} bytes)`);

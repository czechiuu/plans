import assert from 'node:assert/strict'
import { fileURLToPath } from 'node:url'
import { mockApiModule } from './browser-fixture.js'
import { shanghaiDate, addDays } from '../src/domain.js'
import { browserOrigin, launchBrowser } from '../scripts/test-helpers/browser.mjs'
import { report, runCase } from '../scripts/test-helpers/report.mjs'

const ids=['ACTIVITY_DATE_ONLY','ACTIVITY_EDIT_DELETE','CREATE_RETRY','SCHEDULE_TYPE_TIME','FULL_PLAN_PREVIEW']
const cases=[], details=[], check=(id,fn)=>runCase(cases,details,id,fn)
let browser
try {
  browser=await launchBrowser()
  const context=await browser.newContext({viewport:{width:390,height:844},isMobile:true,deviceScaleFactor:1,timezoneId:'America/Los_Angeles',reducedMotion:'reduce'})
  await context.route('**/src/api.js*',route=>route.fulfill({status:200,contentType:'application/javascript',body:mockApiModule()}))
  await context.addInitScript(()=>addEventListener('DOMContentLoaded',()=>{
    if(document.contentType!=='text/html')return
    const mark=document.createElement('div')
    mark.textContent='界面测试 · 合成资料 / 模拟接口'
    Object.assign(mark.style,{position:'fixed',top:'0',right:'0',zIndex:'999',background:'#772f20',color:'white',fontSize:'11px',padding:'4px 8px',pointerEvents:'none'})
    document.body.append(mark)
  }))
  const page=await context.newPage(), pageErrors=[]
  page.on('pageerror',error=>pageErrors.push(error.message))
  await page.goto(browserOrigin())
  await page.getByLabel('密码',{exact:true}).fill('Synthetic-only-password')
  await page.getByRole('button',{name:'登录',exact:true}).click()
  await page.getByRole('heading',{name:'记录当下，再看下一步'}).waitFor()

  await check('ACTIVITY_DATE_ONLY',async()=>{
    await page.getByRole('button',{name:'训练',exact:true}).click()
    await page.locator('.activity-editor summary').click()
    const form=page.locator('[data-form="activity"]')
    await form.locator('[name="record_date"]').fill(shanghaiDate())
    await form.locator('[name="duration_minutes"]').fill('45')
    await form.locator('[name="intensity"]').selectOption('moderate')
    await form.locator('[name="pain"]').selectOption('mild')
    await form.locator('[name="notes"]').fill('合成羽毛球记录')
    await form.getByRole('button',{name:'保存实际运动'}).click()
    await page.getByText('实际运动已保存',{exact:true}).waitFor()
    const rows=await page.evaluate(()=>window.__synthetic.trainingRows())
    assert.equal(rows.length,1)
    assert.equal(rows[0].data.started_at,null)
    assert.equal(rows[0].data.ended_at,null)
    assert.equal(rows[0].data.duration_seconds,2700)
    assert.equal(rows[0].is_shared,false)
    await page.getByRole('button',{name:'趋势',exact:true}).click()
    await page.getByText('羽毛球',{exact:true}).waitFor()
    assert.equal(await page.locator('.stat').filter({has:page.getByText('羽毛球',{exact:true})}).locator('b').innerText(),'1')
    assert.deepEqual(pageErrors,[])
  })
  await check('ACTIVITY_EDIT_DELETE',async()=>{
    await page.getByRole('button',{name:'训练',exact:true}).click()
    await page.getByRole('button',{name:'修改',exact:true}).click()
    const form=page.locator('[data-form="activity"]')
    await form.locator('[name="duration_minutes"]').fill('50')
    await form.getByRole('button',{name:'保存运动修改'}).click()
    await page.getByText('实际运动已保存',{exact:true}).waitFor()
    assert.equal((await page.evaluate(()=>window.__synthetic.trainingRows()))[0].data.duration_seconds,3000)
    page.once('dialog',dialog=>dialog.accept())
    await page.getByRole('button',{name:'删除',exact:true}).click()
    await page.getByText('运动记录已删除',{exact:true}).waitFor()
    assert.equal((await page.evaluate(()=>window.__synthetic.trainingRows())).length,0)
  })
  await check('CREATE_RETRY',async()=>{
    await page.evaluate(()=>window.__synthetic.failNextActivityAck())
    await page.locator('.activity-editor summary').click()
    const form=page.locator('[data-form="activity"]')
    await form.locator('[name="record_date"]').fill(shanghaiDate())
    await form.locator('[name="duration_minutes"]').fill('30')
    await form.getByRole('button',{name:'保存实际运动'}).click()
    await page.getByRole('heading',{name:'运动提交结果待确认'}).waitFor()
    assert.equal((await page.evaluate(()=>window.__synthetic.trainingRows())).length,1)
    await page.getByRole('button',{name:'重试保存这次运动'}).click()
    await page.getByText('实际运动已保存',{exact:true}).waitFor()
    assert.equal((await page.evaluate(()=>window.__synthetic.trainingRows())).length,1)
    await page.getByRole('button',{name:'饮食',exact:true}).click()
    const meal=page.locator('[data-form="meal"]')
    await meal.locator('[data-meal-item] [name="name"]').fill('合成苹果')
    await meal.locator('[data-meal-item] [name="portion"]').fill('一份')
    await meal.locator('[data-meal-item] [name="unit"]').fill('份')
    await page.evaluate(()=>window.__synthetic.failNextMealAck())
    await meal.getByRole('button',{name:'保存餐食'}).click()
    await page.getByRole('heading',{name:'餐食提交结果待确认'}).waitFor()
    assert.equal((await page.evaluate(()=>window.__synthetic.mealRows())).length,1)
    await page.getByRole('button',{name:'重试保存这餐'}).click()
    await page.getByText('餐食已保存',{exact:true}).waitFor()
    assert.equal((await page.evaluate(()=>window.__synthetic.mealRows())).length,1)
  })
  await check('SCHEDULE_TYPE_TIME',async()=>{
    await page.getByRole('button',{name:'明日安排',exact:true}).click()
    const form=page.locator('[data-form="schedule"]')
    await form.locator('[name="exercise_intent"]').selectOption('yes')
    await form.locator('[name="exercise_type"]').selectOption('羽毛球')
    await form.locator('[name="start_time"]').fill('19:00')
    await form.locator('[name="end_time"]').fill('18:00')
    await form.getByRole('button',{name:'保存日程'}).click()
    await page.getByRole('alert').filter({hasText:'结束时间必须更晚'}).waitFor()
    await form.locator('[name="exercise_intent"]').selectOption('yes')
    await form.locator('[name="exercise_type"]').selectOption('羽毛球')
    await form.locator('[name="start_time"]').fill('19:00')
    await form.locator('[name="end_time"]').fill('20:00')
    await form.getByRole('button',{name:'保存日程'}).click()
    await page.getByText('日程已保存',{exact:true}).waitFor()
  })
  await check('FULL_PLAN_PREVIEW',async()=>{
    await page.evaluate(target=>window.__synthetic.seedFullPlan(target),addDays(shanghaiDate(),1))
    await page.locator('[data-action="refresh"]').first().click()
    await page.getByRole('heading',{name:'合成示例：完整三餐与力量训练'}).waitFor()
    for(const title of ['早餐','午餐','晚餐','热身步骤','正式动作','放松步骤']) await page.getByText(title,{exact:false}).first().waitFor()
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
    await page.screenshot({path:fileURLToPath(new URL('../test-results/mobile-full-plan-synthetic.png',import.meta.url)),fullPage:true})
    await page.evaluate(target=>window.__synthetic.seedFullPlan(target),shanghaiDate())
    await page.getByRole('button',{name:'训练',exact:true}).click()
    await page.locator('[data-action="refresh"]').first().click()
    await page.getByRole('button',{name:'今日',exact:true}).click()
    assert.equal(await page.evaluate(()=>{const actions=document.querySelector('.today-actions'),plan=[...document.querySelectorAll('article.card')].find(card=>card.querySelector('h2')?.textContent==='合成示例：完整三餐与力量训练');return Boolean(actions&&plan&&actions.compareDocumentPosition(plan)&Node.DOCUMENT_POSITION_FOLLOWING)}),true)
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
    await page.screenshot({path:fileURLToPath(new URL('../test-results/mobile-full-today-synthetic.png',import.meta.url)),fullPage:true})
    await page.getByRole('button',{name:'训练',exact:true}).click()
    await page.getByRole('button',{name:'播放本地动作示意'}).first().click()
    await page.waitForFunction(()=>Boolean(document.querySelector('.demo-slot object')?.contentDocument?.querySelector('title')))
    await page.screenshot({path:fileURLToPath(new URL('../test-results/mobile-exercise-playing-synthetic.png',import.meta.url)),fullPage:true})
    assert.deepEqual(pageErrors,[])
  })
  await context.close()
} catch(error) {
  if(process.env.TEST_DEBUG_ACTIVITY==='1')process.stderr.write(`${error?.stack || error}\n`)
  if(!cases.some(item=>item.status==='failed')) {cases.push({id:'ACTIVITY_SETUP',status:'failed'});details.push({id:'ACTIVITY_SETUP',error})}
} finally {
  await browser?.close()
  for(const id of ids)if(!cases.some(item=>item.id===id))cases.push({id,status:'notrun'})
  await report('frontend-activity','synthetic-activity-and-full-plan',cases,details)
}
